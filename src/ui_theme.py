def severity_chip(level):
    """level is one of High/Medium/Low (a fixed vocabulary produced by dashboard_utils.risk_level)."""
    level = level if level in ("High", "Medium", "Low") else "Low"
    return f'<span class="chip {level}">{level}</span>'


def status_strip(n_users, model_name, n_alerts_high, data_note="Synthetic dataset"):
    safe_model = str(model_name).replace("<", "").replace(">", "")
    return (
        '<div class="soc-strip">'
        '<span><span class="dot"></span><b>Detection engine online</b></span>'
        f'<span>Model: <b>{safe_model}</b></span>'
        f'<span>Entities monitored: <b>{int(n_users)}</b></span>'
        f'<span>High-severity alerts: <b>{int(n_alerts_high)}</b></span>'
        f'<span>{data_note} - no real data</span>'
        "</div>"
    )


def style_risk_table(df):
    """pandas Styler colouring the Risk level column; used by st.dataframe."""
    colours = {"High": "#F87171", "Medium": "#FBBF24", "Low": "#4ADE80"}

    def _c(v):
        return f"color:{colours.get(v, '#E6EDF7')};font-weight:650"

    return df.style.map(_c, subset=["risk_level"])


